export function slugify(valor) {
    return String(valor)
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
}

export function obterCategorias() {
    return [...categoriasDisponiveis];
}

export function salvarCategorias() {
    try {
        localStorage.setItem("mesaflow-categorias", JSON.stringify(categoriasDisponiveis));
    } catch (erro) {
        console.warn("Não foi possível salvar as categorias.", erro);
    }
}

export function adicionarCategoria(nome) {
    const novaCategoria = String(nome || "").trim();
    const nomeReservado = ["todas", "populares", "promocoes"];

    if (!novaCategoria || nomeReservado.includes(novaCategoria.toLowerCase())) return false;

    const existe = categoriasDisponiveis.some(categoria =>
        categoria.toLowerCase() === novaCategoria.toLowerCase()
    );

    if (existe) return false;

    categoriasDisponiveis.push(novaCategoria);
    salvarCategorias();
    return true;
}

export function renomearCategoria(nomeAntigo, nomeNovo) {
    const novoNome = String(nomeNovo || "").trim();
    const nomeReservado = ["todas", "populares", "promocoes"];
    const indice = categoriasDisponiveis.indexOf(nomeAntigo);

    if (indice === -1 || !novoNome || nomeReservado.includes(novoNome.toLowerCase())) return false;

    const duplicada = categoriasDisponiveis.some(categoria =>
        categoria !== nomeAntigo && categoria.toLowerCase() === novoNome.toLowerCase()
    );

    if (duplicada) return false;

    categoriasDisponiveis[indice] = novoNome;

    produtos.forEach(produto => {
        produto.categorias = (produto.categorias || []).map(categoria =>
            categoria === nomeAntigo ? novoNome : categoria
        );
    });

    if (coresCategorias[nomeAntigo]) {
        coresCategorias[novoNome] = coresCategorias[nomeAntigo];
        delete coresCategorias[nomeAntigo];
    }

    salvarCategorias();
    salvarProdutos();
    return true;
}

export function formatarPreco(preco) {
    if (preco === null || preco === undefined || preco === "") {
        return "Preço não informado";
    }

    return Number(preco).toLocaleString("pt-BR", {
        style: "currency",
        currency: "BRL"
    });
}

export function salvarProdutos() {
    try {
        localStorage.setItem("mesaflow-produtos", JSON.stringify(produtos));
    } catch (erro) {
        console.warn("Não foi possível salvar os produtos.", erro);
    }
}

/* Mantém compatibilidade com dados antigos que ainda tenham "categoria". */
try {
    const categoriasSalvas = localStorage.getItem("mesaflow-categorias");

    if (categoriasSalvas) {
        const listaCategorias = JSON.parse(categoriasSalvas);

        if (Array.isArray(listaCategorias)) {
            categoriasDisponiveis.splice(0, categoriasDisponiveis.length, ...listaCategorias);
        }
    }

    const dadosSalvos = localStorage.getItem("mesaflow-produtos");

    if (dadosSalvos) {
        const listaSalva = JSON.parse(dadosSalvos);

        if (Array.isArray(listaSalva)) {
            produtos.splice(0, produtos.length, ...listaSalva.map(produto => ({
                ...produto,
                categorias: produto.categorias || (produto.categoria ? [produto.categoria] : []),
                avaliacao: Number(produto.avaliacao) || 0,
                promocao: Boolean(produto.promocao),
                precoPromocional: produto.precoPromocional ?? null
            })));
            produtos.forEach(produto => {
                (produto.categorias || []).forEach(categoria => {
                    if (!categoriasDisponiveis.includes(categoria)) categoriasDisponiveis.push(categoria);
                });
            });
        }
    }
} catch (erro) {
    console.warn("Não foi possível carregar os produtos salvos.", erro);
}
